"use client";
import { useCallback, useEffect, useRef, useState } from "react";
import Link from "next/link";
import ProductViewer from "./ProductViewer";
import { withBase, type ModelRecord } from "@/lib/client";

const PAGE = 12;

function label(m: ModelRecord) {
  if (m.example) return "Example";
  if (m.kind === "photo") return "Built by a visitor";
  if (m.kind === "prompt") return "Made from text";
  return "Built live";
}

function ago(ms: number) {
  const s = Math.max(1, Math.round((Date.now() - ms) / 1000));
  if (s < 60) return "just now";
  const m = Math.round(s / 60); if (m < 60) return `${m} min ago`;
  const h = Math.round(m / 60); if (h < 48) return `${h} h ago`;
  return `${Math.round(h / 24)} days ago`;
}

function source(m: ModelRecord) {
  if (m.kind === "photo") return "Uploaded photo";
  if (m.kind === "prompt") return "Text prompt";
  if (m.domain === "demo") return "Lux3D sample";
  return m.domain?.replace(/^www\./, "") ?? "";
}

// Every model built on the site, newest first. Grows as people use it:
// polls for new builds and listens for builds made on this page.
export default function Showcase({ initial, total: initialTotal }: { initial: ModelRecord[]; total: number }) {
  const [items, setItems] = useState(initial);
  const [total, setTotal] = useState(initialTotal);
  const [loading, setLoading] = useState(false);
  const [fresh, setFresh] = useState<Set<string>>(new Set());
  const itemsRef = useRef(items);
  itemsRef.current = items;

  const mergeNew = useCallback((incoming: ModelRecord[], newTotal?: number) => {
    const have = new Set(itemsRef.current.map((m) => m.id));
    const added = incoming.filter((m) => !have.has(m.id));
    if (added.length) {
      setItems((cur) => [...added, ...cur]);
      setFresh((f) => new Set([...f, ...added.map((m) => m.id)]));
    }
    if (newTotal !== undefined) setTotal(newTotal);
  }, []);

  // pick up builds from other visitors
  useEffect(() => {
    const id = setInterval(async () => {
      try {
        const r = await fetch(withBase(`/api/models?limit=${PAGE}`)).then((x) => x.json());
        mergeNew(r.models.filter((m: ModelRecord) => !m.example), r.total);
      } catch { /* ignore */ }
    }, 20000);
    return () => clearInterval(id);
  }, [mergeNew]);

  // the visitor's own build, the moment it lands
  useEffect(() => {
    const on = (e: Event) => {
      const rec = (e as CustomEvent<ModelRecord>).detail;
      if (!rec?.glb || itemsRef.current.some((m) => m.id === rec.id)) return;
      setTotal((t) => t + 1);
      mergeNew([rec]);
    };
    window.addEventListener("showroom:built", on);
    return () => window.removeEventListener("showroom:built", on);
  }, [mergeNew]);

  async function more() {
    setLoading(true);
    try {
      const r = await fetch(withBase(`/api/models?limit=${PAGE}&offset=${items.length}`)).then((x) => x.json());
      const have = new Set(items.map((m) => m.id));
      setItems((cur) => [...cur, ...r.models.filter((m: ModelRecord) => !have.has(m.id))]);
      setTotal(r.total);
    } finally { setLoading(false); }
  }

  return (
    <section className="wrap" style={{ marginTop: 72 }} id="showcase">
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "end", gap: 12, flexWrap: "wrap" }}>
        <div>
          <div className="eyebrow">Showcase · growing live</div>
          <h2 className="display" style={{ fontSize: 36, margin: "8px 0 4px" }}>
            <span style={{ color: "var(--accent)" }}>{total}</span> products built in 3D so far
          </h2>
          <p className="muted" style={{ margin: "0 0 18px" }}>Every model here was generated by Lux3D from a single photo or a line of text — newest first.</p>
        </div>
        <Link href="/explore" className="btn">Explore stores →</Link>
      </div>
      <div className="grid">
        {items.map((m) => (
          <div key={m.id} className={`card showcase-card${fresh.has(m.id) ? " is-new" : ""}`} style={{ overflow: "hidden" }}>
            <div style={{ aspectRatio: "1/1", background: "var(--bg-2)", position: "relative" }}>
              <ProductViewer src={m.glb!} alt={m.title} poster={m.image} ar={false} lazy />
              <span className={`pill ${m.example ? "" : "pill-live"}`} style={{ position: "absolute", left: 10, top: 10 }}>{label(m)}</span>
              {fresh.has(m.id) && <span className="pill pill-accent" style={{ position: "absolute", right: 10, top: 10 }}>New</span>}
            </div>
            <div style={{ padding: 14 }}>
              <div style={{ fontWeight: 600, fontSize: 14, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>{m.title}</div>
              <div className="faint" style={{ fontSize: 13, display: "flex", justifyContent: "space-between", gap: 8 }}>
                <span>{source(m)}</span>
                {!m.example && <span>{ago(m.createdAt)}</span>}
              </div>
            </div>
          </div>
        ))}
      </div>
      {items.length < total && (
        <div style={{ textAlign: "center", marginTop: 20 }}>
          <button className="btn" onClick={more} disabled={loading}>{loading ? <span className="spin" /> : `Show more (${total - items.length} more)`}</button>
        </div>
      )}
    </section>
  );
}
